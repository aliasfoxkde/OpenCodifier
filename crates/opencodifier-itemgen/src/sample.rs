    #[test]
    fn the_score_rubric_truth_table_is_exact() {
        // Each row: (healthy, degraded, down) → level. Covers every
        // branch and the branch boundaries (exact half, strict majority,
        // tie-breaks) — the rubric stated word-for-word in SCORE_LEVELS.
        let table = [
            ((1, 0, 3), 0), // 2·3 > 4: downs are the majority
            ((0, 0, 1), 0), // 2·1 > 1: a lone down report is already critical
            ((3, 0, 1), 2), // one failure, healthy leads
            ((2, 3, 0), 2), // nothing down, degraded leads
            ((2, 0, 2), 1), // 2·2 = total is NOT a majority, but failures reach half
            ((4, 2, 0), 3), // nothing down, healthy ≥ degraded
            ((2, 2, 0), 3), // the ≥ boundary: healthy EQUALS degraded
            ((0, 3, 1), 1), // failures reach half (2·4 ≥ 4), downs not majority
            ((1, 1, 1), 1), // 2·2 ≥ 3 with one down
            ((5, 0, 1), 2), // one failure, healthy dominates
            ((1, 0, 0), 3), // single healthy report is healthy
        ];
        for ((h, d, x), expected) in table {
            assert_eq!(health_level(h, d, x), expected, "counts ({h},{d},{x})");
        }
    }

    #[test]
    fn counts_for_level_always_realizes_its_level() {
        // Property, not spot checks: for every level and every total the
        // sampler can draw, the constructed counts must land in that
        // level's band. This is the sampler invariant the level-spread
        // guarantee rests on.
        let mut rng = Rng::new(8);
        for level in 0..4 {
            for total in 1..=15 {
                // Infeasible combos the sampler never draws: level 1
                // needs a down (total ≥ 2); level 2's failure-present
                // branch needs total ≥ 4 and the sampler bumps the
                // draw to that floor.
                if level == 1 && total < 2 || level == 2 && total < 4 {
                    continue;
                }
                let (h, d, x) = counts_for_level(level, total, &mut rng);
                assert_eq!(h + d + x, total, "counts must sum to total");
                assert_eq!(health_level(h, d, x), level, "level {level} total {total}");
            }
        }
    }

    #[test]
    fn score_items_spread_across_all_four_levels() {
        let mut rng = Rng::new(9);
        let mut seen = [0usize; 4];
        for _ in 0..200 {
            let sampled = sample(Family::ScoreBoard, &mut rng);
            let (h, d, x) = count_statuses(&sampled.facts);
            // The stored gold must agree with the constructed fact set.
            assert_eq!(sampled.gold, health_level(h, d, x).to_string());
            seen[sampled.gold.parse::<usize>().unwrap()] += 1;
        }
        for (level, count) in seen.iter().enumerate() {
            assert!(*count >= 20, "level {level} drew only {count} of 200");
        }
    }

    #[test]
    fn corrupt_to_pair_flips_exactly_one_fact_and_moves_the_gold() {
        // Draw until the shape matches, then check the pair contract:
        // same length, one health fact different, gold moved to the
        // direct dependent, old gold demoted to a healthy peer.
        let mut rng = Rng::new(10);
        let mut paired = 0;
        for _ in 0..200 {
            let base = sample(Family::RootCauseChain, &mut rng);
            let Some(twin) = corrupt_to_pair(&base) else { continue };
            paired += 1;
            assert_eq!(base.facts.len(), twin.facts.len(), "one-fact flip, not a rewrite");
            let diffs: Vec<(&RelationalFact, &RelationalFact)> =
                base.facts.iter().zip(&twin.facts).filter(|(a, b)| a != b).collect();
            assert_eq!(diffs.len(), 1, "expected exactly one changed fact, got {diffs:?}");
            assert!(matches!(diffs[0].0, RelationalFact::Health { status: Health::Down, .. }));
            assert!(matches!(diffs[0].1, RelationalFact::Health { status: Health::Healthy, .. }));
            assert_ne!(base.gold, twin.gold);
            // The new gold must be the direct dependent of the old gold.
            assert!(
                base.facts.iter().any(|f| matches!(f,
                    RelationalFact::DependsOn { dependent, dependency }
                    if *dependent == twin.gold && *dependency == base.gold)),
                "twin gold is not the old gold's direct dependent"
            );
        }
        assert!(paired >= 50, "the pair shape never drew: {paired}/200");
    }

    /// The status tally reads health facts only — ordering facts
    /// (`DependsOn`, `RestoresAfter`) carry no health signal and must
