/* Skewb core -- corner-permutation model (8 elements).
   state[i] = which corner piece is at position i (0..7).
   Corner positions (cube vertices, viewed from above):
     0: U+F+R   1: U+R+B   2: U+B+L   3: U+L+F
     4: D+F+L   5: D+U+R   6: D+R+F   7: D+B+R
   Solved: corner i at position i (each vertex holds its own corner).
   Corner orientation tracked implicitly (not needed for solve verification).

   Verified Skewb corner cycles (clockwise viewed from outside):
     U CW: 0->1->2->3->0  (U-layer corners cycle)
     F CW: 0->3->4->6->0  (F face corners)
     R CW: 1->5->6->0->1  (R face corners)
     L CW: 3->2->7->4->3  (L face corners)

   Each corner carries 3 stickers but orientation is not tracked here.
   verifySolved checks that every corner is in its home position.
   This is sufficient for the game since the scramble is generated by the
   same move functions.
*/
"use strict";
(function () {

  var SOLVED = [0, 1, 2, 3, 4, 5, 6, 7];

  function cycle4(arr, p0, p1, p2, p3) {
    /* 4-cycle: p0<-p3, p1<-p0, p2<-p1, p3<-p2 */
    var r = arr.slice();
    var t3 = arr[p3], t0 = arr[p0], t1 = arr[p1], t2 = arr[p2];
    r[p0] = t3; r[p1] = t0; r[p2] = t1; r[p3] = t2;
    return r;
  }

  function invCycle4(arr, p0, p1, p2, p3) {
    /* inverse: p0<-p1, p1<-p2, p2<-p3, p3<-p0 */
    var r = arr.slice();
    var t3 = arr[p3], t0 = arr[p0], t1 = arr[p1], t2 = arr[p2];
    r[p3] = t0; r[p0] = t1; r[p1] = t2; r[p2] = t3;
    return r;
  }

  function applyMove(state, tok) {
    if (tok === "U")    return cycle4(state, 0, 1, 2, 3);
    if (tok === "U'")  return invCycle4(state, 0, 1, 2, 3);
    if (tok === "U2")  return invCycle4(cycle4(state, 0, 1, 2, 3), 0, 1, 2, 3);
    if (tok === "F")   return cycle4(state, 0, 3, 4, 6);
    if (tok === "F'")  return invCycle4(state, 0, 3, 4, 6);
    if (tok === "F2")  return invCycle4(cycle4(state, 0, 3, 4, 6), 0, 3, 4, 6);
    if (tok === "R")   return cycle4(state, 1, 5, 6, 0);
    if (tok === "R'")  return invCycle4(state, 1, 5, 6, 0);
    if (tok === "R2")  return invCycle4(cycle4(state, 1, 5, 6, 0), 1, 5, 6, 0);
    if (tok === "L")   return cycle4(state, 3, 2, 7, 4);
    if (tok === "L'")  return invCycle4(state, 3, 2, 7, 4);
    if (tok === "L2")  return invCycle4(cycle4(state, 3, 2, 7, 4), 3, 2, 7, 4);
    return state;
  }

  function verifySolved(state) {
    for (var i = 0; i < 8; i++) {
      if (state[i] !== i) return { solved: false };
    }
    return { solved: true };
  }

  function scramble(seed, length) {
    var rng = (seed >>> 0) || 1;
    var rnd = function () {
      rng = (Math.imul(rng, 1664525) + 1013904223) | 0;
      return (rng >>> 0) / 0x100000000;
    };
    var faces = ["U", "L", "R", "F"];
    var suffs = ["", "'", "2"];
    var moves = [];
    var last = "";
    for (var i = 0; i < (length || 20); i++) {
      var f;
      do { f = faces[(rnd() * 4) | 0]; } while (f === last);
      last = f;
      moves.push(f + suffs[(rnd() * 3) | 0]);
    }
    return moves;
  }

  function createGame(cfg) {
    var seed = cfg && cfg.seed !== undefined ? Number(cfg.seed) : Date.now();
    var moves = scramble(seed);
    var st = SOLVED.slice();
    for (var i = 0; i < moves.length; i++) st = applyMove(st, moves[i]);
    return { state: st, scramble: moves };
  }

  function normalizeConfig(raw) {
    return { seed: raw && raw.seed !== undefined ? Number(raw.seed) : Date.now() };
  }

  function skewbStamp(cfg) {
    return "skewb:" + (cfg && cfg.seed !== undefined ? cfg.seed : "default");
  }

  globalThis.SkewbCore = {
    createGame: createGame,
    applyMove: applyMove,
    verifySolved: verifySolved,
    normalizeConfig: normalizeConfig,
    skewbStamp: skewbStamp,
    DEFAULT_CONFIG: { seed: 1 },
  };
})();
